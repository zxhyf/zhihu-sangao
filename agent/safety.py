def _find(text: str, words: list[str]) -> list[str]:
    return [w for w in words if w in text]


def check_text(text: str) -> dict:
    """纯文本安全审查。返回 {level, category, title, actions, matched}。"""
    t = (text or "").strip()
    if not t:
        return {"level": "none"}

    for category, words, why, action in RED_FLAG_RULES:
        hit = _find(t, words)
        if hit:
            return {
                "level": "emergency",
                "category": category,
                "title": f"检测到{category}相关信号：{'、'.join(hit[:3])}",
                "why": why,
                "actions": action,
                "matched": hit,
            }

    # 数值型急症：血压 ≥180/110
    for m in re.finditer(r"(\d{2,3})\s*(?:/|／|比|、)\s*(\d{2,3})", t):
        sys_v, dia_v = int(m.group(1)), int(m.group(2))
        if 30 <= dia_v <= 200 and 30 <= sys_v <= 300:
            if sys_v >= 180 or dia_v >= 110:
                return {
                    "level": "emergency",
                    "category": "高血压急症",
                    "title": f"血压 {sys_v}/{dia_v} mmHg 达到 3 级高血压范围",
                    "why": "血压 ≥180/110 mmHg 属于高血压急症警戒线",
                    "actions": "静坐休息 5 分钟后复测；若复测仍 ≥180/110，或伴头痛、胸痛、呼吸困难、视物模糊，立即拨打 120。不要自行加服降压药。",
                    "matched": [f"{sys_v}/{dia_v}"],
                }

    # 血糖 <3.9 伴意识改变 / >16.7
    for m in re.finditer(r"血糖[^\d]{0,6}(\d{1,2}(?:\.\d+)?)", t):
        v = float(m.group(1))
        if v >= 16.7:
            return {
                "level": "emergency",
                "category": "高血糖急症",
                "title": f"血糖 {v} mmol/L 明显升高",
                "why": "血糖 ≥16.7 mmol/L 有酮症酸中毒风险",
                "actions": "立即联系医生或前往急诊；多饮水（无心衰、无水肿时），不要自行追加胰岛素。",
                "matched": [str(v)],
            }
        if v < 3.9:
            return {
                "level": "urgent",
                "category": "低血糖",
                "title": f"血糖 {v} mmol/L 属于低血糖",
                "why": "血糖 <3.9 mmol/L 需立即纠正",
                "actions": "立即进食 15 g 速效碳水（3–4 块方糖或 150 mL 果汁），15 分钟后复测；若出现意识改变立即拨打 120。",
                "matched": [str(v)],
            }
    return {"level": "none"}


def check_prescription(text: str) -> dict:
    """处方红线识别：是否在请求调药。"""
    t = (text or "").strip()
    hits: list[str] = []
    for pat in PRESCRIPTION_PATTERNS:
        for m in re.finditer(pat, t):
            hits.append(m.group(0))
    if hits:
        return {
            "level": "prescription",
            "matched": sorted(set(hits)),
            "title": "涉及药物调整",
            "message": (
                "药物是否需要加量、减量、更换或停用，必须由开药医生结合你的血压/血糖记录、"
                "肝肾功能和并发症情况判断。我不能给出调药建议，但可以帮你把数据整理清楚，"
                "方便复诊时和医生沟通。"
            ),
            "actions": [
                "带上最近 2 周的血压/血糖记录复诊",
                "把正在服用的全部药物（含保健品、中成药）列成清单给医生看",
                "出现头晕、心慌、水肿等不适时尽快就医",
            ],
        }
    return {"level": "none"}


def evaluate(text: str) -> dict:
    """完整安全评估入口。"""
    em = check_text(text)
    if em.get("level") == "emergency":
        return em
    rx = check_prescription(text)
    if rx.get("level") == "prescription":
        return rx
    if em.get("level") == "urgent":
        return em
    return {"level": "none"}
